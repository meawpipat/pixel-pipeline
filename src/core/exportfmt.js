// §6 export formats (v3.8, D16): 2-bit pixel plane + 1-bit mask + reference point, as C header, .bin and 4-grey PNG.
// No dithering here: consumers scale first, then dither at screen pixels (§2.4) — see pp_draw in the header.
import { TRANSPARENT } from './config.js';
import { packPlane, canvasReference } from './dither.js';

export const symbolBase = (name) => name.replace(/\.(png|bin)$/, '').replace(/-fat/, '_fat');
export const FORMATS = ['h', 'bin', 'png'];

/** §6 "files of a group" in art/export/{species}/: `{group}.h` and `{group}_{anim}_{nn}[_ink|_mask].(bin|png)`. */
export function isGroupExportFile(f, groupId) {
  if (f === `${groupId}.h`) return true;
  const esc = groupId.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`^${esc}_[a-z0-9]+_\\d{2}(_ink|_mask)?\\.(bin|png)$`).test(f);
}

/** 2 bits/pixel, row-major, leftmost pixel in bits 7–6; transparent → 3. 1024 bytes for 64x64. */
export function packPx(c) {
  const out = new Uint8Array(Math.ceil(c.w / 4) * c.h);
  const rowBytes = Math.ceil(c.w / 4);
  for (let y = 0; y < c.h; y++) for (let x = 0; x < c.w; x++) {
    const v = c.I[y * c.w + x];
    out[y * rowBytes + (x >> 2)] |= (v === TRANSPARENT ? 3 : v) << (6 - 2 * (x & 3));
  }
  return out;
}
export const maskOf = (c) => Uint8Array.from(c.I, (v) => (v === TRANSPARENT ? 0 : 1));

/** Everything the formats need for one frame. */
export function frameData(c) {
  if (c.w !== 64 || c.h !== 64) throw new Error(`export needs a 64x64 canvas (D1), got ${c.w}x${c.h}`);
  const [rx, ry] = canvasReference(c);
  return { px: packPx(c), mask: packPlane(maskOf(c), c.w, c.h), ref: [rx, ry] };
}

/** .bin = px (1024 B) + mask (512 B) + ref_x, ref_y (1 B each) = 1538 bytes. */
export function toBin(fd) {
  const out = new Uint8Array(fd.px.length + fd.mask.length + 2);
  out.set(fd.px); out.set(fd.mask, fd.px.length);
  out[out.length - 2] = fd.ref[0]; out[out.length - 1] = fd.ref[1];
  return out;
}

const hexRow = (bytes) => {
  const lines = [];
  for (let i = 0; i < bytes.length; i += 16) lines.push('  ' + Array.from(bytes.subarray(i, i + 16), (b) => '0x' + b.toString(16).padStart(2, '0')).join(', '));
  return lines.join(',\n');
};

/**
 * C header for one group. frames: [{ name, anim, frame, fd }] sorted by anim then frame.
 * tilesId: 8 hex chars identifying cfg.dither.tiles (a header mix with other tiles is a compile error).
 */
export function toHeader(groupId, frames, { toolVersion, anchor, tiles, tilesId, pixelHash }) {
  const g = groupId.replace(/-fat/, '_fat');
  const G = g.toUpperCase();
  const t = (v) => `{ { ${tiles[String(v)][0].join(', ')} }, { ${tiles[String(v)][1].join(', ')} } }`;
  const out = [];
  out.push(`// Generated by pixelpipe ${toolVersion} — do not edit. Group: ${groupId}, dither anchor: ${anchor}, pixel_hash: ${pixelHash}`);
  out.push('// Layout (spec §6, D16): 64x64. px: 2 bpp, row-major, leftmost pixel in bits 7-6, 0 black .. 3 white (transparent = 3), 1024 B.');
  out.push('// mask: 1 bpp, MSB = leftmost, 1 = opaque, 512 B. Draw with pp_draw: scale first, then dither at screen pixels (§2.4).');
  out.push('#pragma once', '#include <stdint.h>', '#ifndef PROGMEM', '#define PROGMEM', '#endif', '');
  out.push(`#if defined(PIXELPIPE_TILES_ID) && PIXELPIPE_TILES_ID != 0x${tilesId}`);
  out.push('#error "pixelpipe: headers exported with different dither tiles"');
  out.push('#endif');
  out.push('#ifndef PIXELPIPE_V2_COMMON', '#define PIXELPIPE_V2_COMMON', `#define PIXELPIPE_TILES_ID 0x${tilesId}`);
  out.push('typedef struct { const uint8_t* px; const uint8_t* mask; uint8_t ref_x, ref_y; } pp_frame_t;');
  out.push(`static const uint8_t pp_tiles[4][2][2] = { ${[0, 1, 2, 3].map(t).join(', ')} };`);
  out.push(
    '/* Reference renderer (normative, spec §2.4). Does not clip: plot() must ignore pixels outside the screen.',
    '   Reads PROGMEM data by plain pointer access (valid on ESP32 / CoreInk). On AVR, include this header after',
    '   <avr/pgmspace.h> / Arduino.h and read the arrays with pgm_read_byte instead. */',
    'static inline void pp_draw(const pp_frame_t* f, int x0, int y0, int scale, int sprite_anchor, void (*plot)(int x, int y, int black)) {',
    '  int ax = sprite_anchor ? f->ref_x : 0, ay = sprite_anchor ? f->ref_y : 0;',
    '  for (int y = 0; y < 64; y++) for (int x = 0; x < 64; x++) {',
    '    if (!((f->mask[y * 8 + (x >> 3)] >> (7 - (x & 7))) & 1)) continue;',
    '    int v = (f->px[y * 16 + (x >> 2)] >> (6 - 2 * (x & 3))) & 3;',
    '    for (int py = 0; py < scale; py++) for (int px = 0; px < scale; px++)',
    '      plot(x0 + x * scale + px, y0 + y * scale + py, pp_tiles[v][((y - ay) * scale + py) & 1][((x - ax) * scale + px) & 1]);',
    '  }',
    '}',
  );
  out.push('#endif', '');
  out.push(`#define ${G}_DITHER_ANCHOR_SPRITE ${anchor === 'sprite' ? 1 : 0}`);
  for (const f of frames) {
    const s = symbolBase(f.name);
    out.push(`static const uint8_t ${s}_px[1024] PROGMEM = {\n${hexRow(f.fd.px)}\n};`);
    out.push(`static const uint8_t ${s}_mask[512] PROGMEM = {\n${hexRow(f.fd.mask)}\n};`);
  }
  out.push('');
  const anims = [...new Set(frames.map((f) => f.anim))];
  for (const a of anims) {
    const fs = frames.filter((f) => f.anim === a);
    out.push(`static const pp_frame_t ${g}_${a}[] = {\n${fs.map((f) => `  { ${symbolBase(f.name)}_px, ${symbolBase(f.name)}_mask, ${f.fd.ref[0]}, ${f.fd.ref[1]} }`).join(',\n')}\n};`);
    out.push(`#define ${(g + '_' + a).toUpperCase()}_COUNT ${fs.length}`);
  }
  return out.join('\n') + '\n';
}
